def answer_html(question: str, a, rows: list[dict], when: datetime | None = None) -> str:
    """The body of the PDF of one answer. `rows` are the figures as components.input_rows() gives them."""
    when = when or datetime.now()
    parts = [f"<h1>{_e(question)}</h1>", f'<p class="meta">FinSight · Annual report Q&amp;A · {when:%d %b %Y, %H:%M}</p>']
    parts += _answer_parts(a, rows)
    parts.append(f'<p class="notice">{_e(NOTICE)}</p>')
    return "\n".join(parts)


def _answer_parts(a, rows: list[dict]) -> list[str]:
    """One answer as HTML: the sentence, formula, key points, figures, notes and sources."""
    parts = [f'<p class="answer">{_e(a.answer)}</p>']
    if getattr(a, "formula", None):
        parts.append(f"<p><b>Formula:</b> {_e(a.formula)}</p>")
    if getattr(a, "key_points", None):
        parts.append("<h2>Key points</h2><ul>" + "".join(f"<li>{_e(k.point)} <span class=\"small\">[{_e(k.citation)}]</span></li>"
                                                         for k in a.key_points) + "</ul>")
    if rows:
        cols = list(rows[0])
        head = "".join(f'<th class="num">{_e(c)}</th>' if c == "Value" else f"<th>{_e(c)}</th>" for c in cols)
        body = "".join("<tr>" + "".join(f'<td class="num">{_e(r[c])}</td>' if c == "Value" else f"<td>{_e(r[c])}</td>" for c in cols) + "</tr>"
                       for r in rows)
        parts.append(f"<h2>Figures used</h2><table><tr>{head}</tr>{body}</table>"
                     '<p class="small">"Read from" gives the page of the PDF file of the report, not the number printed on the page.</p>')
    for c in getattr(a, "caveats", None) or []:
        parts.append(f'<p class="small">Note: {_e(c)}</p>')
    cites = list(dict.fromkeys(list(getattr(a, "citations", None) or []) + [k.citation for k in getattr(a, "key_points", None) or []]))
    if cites:
        parts.append(f"<p><b>Sources:</b> {_e(', '.join(cites))}</p>")
    return parts


# NEW (24 Nov 2026, later): the complete conversation as one PDF.
# WHY: the button exported only the answer it stood under. The request after trying it: the PDF must hold the
#      whole chat, every question with its reply, in the order they were asked.
#   - A verified answer is written in full (figures, pages, key points, sources), as before.
#   - A reply that is not a verified answer (a question back to the user, a refusal, an answer that failed the
#     check) is written as plain text with a label that says what it is, so it cannot be mistaken for a checked
#     figure. This keeps the rule of the earlier design: only checked answers are presented as answers.
_LABELS = {"clarify": "FinSight asked", "refused": "Refused", "escalated": "Not verified"}


def conversation_html(turns: list[dict], when: datetime | None = None) -> str:
    """`turns` is the history of the chat screen: {"role": "user" | "assistant", "content": text, "agent": answer or None}."""
    from components import can_export, input_rows
    when = when or datetime.now()
    asked = sum(1 for t in turns if t.get("role") == "user")
    parts = ["<h1>FinSight conversation</h1>",
             f'<p class="meta">Annual report Q&amp;A · {when:%d %b %Y, %H:%M} · {asked} question{"s" if asked != 1 else ""}</p>']
    n = 0
    for t in turns:
        if t.get("role") == "user":
            n += 1
            parts.append(f"<h2>{n}. {_e(t.get('content'))}</h2>")
            continue
        a = t.get("agent")
        if a is not None and can_export(a):
            parts += _answer_parts(a, input_rows(a))
        else:
            label = _LABELS.get(getattr(a, "status", None), "Reply")
            text = (getattr(a, "answer", None) or getattr(a, "clarifying_question", None)) if a is not None else None
            parts.append(f'<p><span class="small">{_e(label)}:</span> {_e(text or t.get("content"))}</p>')
    parts.append(f'<p class="notice">{_e(NOTICE)}</p>')
    return "\n".join(parts)


def conversation_pdf(turns: list[dict], when: datetime | None = None) -> bytes:
    """The whole conversation as the bytes of a PDF file."""
    return _render(conversation_html(turns, when))


def answer_pdf(question: str, a, rows: list[dict] | None = None, when: datetime | None = None) -> bytes:
    """The answer as the bytes of a PDF file (A4, as many pages as it needs)."""
    if rows is None:
        from components import input_rows
        rows = input_rows(a)
    return _render(answer_html(question, a, rows, when))


# CHANGED (24 Nov 2026, later): the lay-out loop moved from answer_pdf into _render, so both PDFs use it.
def _render(body: str) -> bytes:
    import pymupdf
    out = io.BytesIO()
    writer = pymupdf.DocumentWriter(out)
    story = pymupdf.Story(html=body, user_css=CSS)
    page = pymupdf.paper_rect("a4")
    inside = page + (50, 50, -50, -50)
    more, pages = 1, 0
    while more and pages < 200:                               # a guard against an endless loop (was 30 for one answer)
        device = writer.begin_page(page)
        more, _ = story.place(inside)
        story.draw(device)
        writer.end_page()
        pages += 1
    writer.close()
    return out.getvalue()


def file_name(question: str) -> str:
    """FinSight_what-was-infosys-consolidated-net-profit.pdf"""
    slug = re.sub(r"[^a-z0-9]+", "-", (question or "").lower()).strip("-")[:48].strip("-") or "answer"
    return f"FinSight_{slug}.pdf"
