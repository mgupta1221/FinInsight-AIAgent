"""A verified answer as a PDF file, for the "Export to PDF" button of the chat screen.

NEW FILE (24 Nov 2026, mentor's review).

WHY: an answer could be exported only as a Markdown note, in two steps (a DRAFT, then Approve). The review asked
     for one button that downloads a PDF straight away. This file builds that PDF from the answer object: the
     question, the answer sentence, the formula, the figures with the page each was read from, the key points
     of a summary with their citations, the notes of the agent, and the sources.

What is kept from the DRAFT / Approve design: only an answer that passed the agent's check can be exported
(components.can_export), and every PDF carries the notice below, so the warning travels with the document.

How: the page is written as simple HTML and laid out by PyMuPDF (already a dependency of the project, used to
read the reports), which also breaks it over several pages when it is long. No other library is needed.
No Streamlit import here, so it can be unit-tested without a browser (tests/test_app.py).
"""
from __future__ import annotations

import html
import io
import re
from datetime import datetime

NOTICE = ("Generated by FinSight from the companies' annual reports. Check each figure against the cited page "
          "before use. Not investment advice.")

CSS = """
body { font-family: sans-serif; font-size: 10.5pt; color: #1b2a2a; }
h1 { font-size: 15pt; color: #0f3d3e; margin-bottom: 2pt; }
h2 { font-size: 11.5pt; color: #0f3d3e; margin-top: 14pt; margin-bottom: 4pt; }
p { margin-top: 4pt; margin-bottom: 4pt; }
.meta { color: #5f7272; font-size: 9pt; }
.answer { font-size: 12pt; margin-top: 10pt; }
.small { font-size: 9pt; color: #5f7272; }
table { border-collapse: collapse; width: 100%; }
th { background-color: #eaf2ef; text-align: left; font-size: 9pt; padding: 3pt; border: 0.5pt solid #9cc3b5; }
td { font-size: 9pt; padding: 3pt; border: 0.5pt solid #c9d8d3; }
.num { text-align: right; }
li { margin-bottom: 4pt; }
.notice { color: #5f7272; font-size: 8.5pt; margin-top: 20pt; border-top: 0.5pt solid #c9d8d3; padding-top: 6pt; }
"""


def _e(text) -> str:
    """Text made safe for HTML. The rupee sign is written "Rs": the fonts built into a PDF do not have it."""
    return html.escape(str(text if text is not None else "")).replace("₹", "Rs ")


